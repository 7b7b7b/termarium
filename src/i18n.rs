pub fn moon_phase_name(language: Language, phase: MoonPhase) -> &'static str {
    let key = match phase.phase_fraction {
        value if !(0.03..=0.97).contains(&value) => "new_moon",
        value if value < 0.22 => "waxing_crescent",
        value if value < 0.28 => "first_quarter",
        value if value < 0.47 => "waxing_gibbous",
        value if value < 0.53 => "full_moon",
        value if value < 0.72 => "waning_gibbous",
        value if value < 0.78 => "last_quarter",
        _ => "waning_crescent",
    };
    tr(language, key)
}

pub fn moon_symbol(phase: MoonPhase) -> &'static str {
    match phase.phase_fraction {
        value if !(0.03..=0.97).contains(&value) => "○",
        value if value < 0.22 => "◔",
        value if value < 0.28 => "◐",
        value if value < 0.47 => "◕",
        value if value < 0.53 => "●",
        value if value < 0.72 => "◕",
        value if value < 0.78 => "◑",
        _ => "◔",
    }
}
